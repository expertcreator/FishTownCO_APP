/**
 * Governates (Jordan) or provinces (Pakistan) for the city/province pickers.
 * Use this so the list is never built via fragile index chains.
 */
export function getProvinceOrGovernorateOptions(country: CountryName): {
  label: string;
  value: ProvinceName;
}[] {
  if (country === "Pakistan") {
    return (Object.keys(LOCATION_DATA.Pakistan) as PakistanProvinceName[]).map(
      (name) => ({ label: name, value: name as ProvinceName })
    );
  }
  return (Object.keys(LOCATION_DATA.Jordan) as JordanProvinceName[]).map(
    (name) => ({ label: name, value: name as ProvinceName })
  );
}

/**
 * Map API/legacy province or governorate strings to keys in `LOCATION_DATA[country]`.
 * Handles exact match, case-insensitive match, and short names like "Amman" → "Amman Governorate" (Jordan).
 */
export function resolveProvinceKey(
  country: CountryName,
  raw: string | null | undefined
): ProvinceName | null {
  const t = normalizeLocationString(String(raw));
  if (!t) {
    return null;
  }
  if (country === "Pakistan") {
    const map = LOCATION_DATA.Pakistan;
    const keys = Object.keys(map) as PakistanProvinceName[];
    if (t in map) {
      return t as ProvinceName;
    }
    const byCi = keys.find((k) => k.toLowerCase() === t.toLowerCase());
    return (byCi ?? null) as ProvinceName | null;
  }
  const map = LOCATION_DATA.Jordan;
  const keys = Object.keys(map) as JordanProvinceName[];
  if (t in map) {
    return t as ProvinceName;
  }
  const byCi = keys.find((k) => k.toLowerCase() === t.toLowerCase());
  if (byCi) {
    return byCi;
  }
  const byPrefix = keys.find(
    (k) =>
      k.toLowerCase().startsWith(t.toLowerCase()) ||
      k.toLowerCase().split(" ")[0] === t.toLowerCase()
  );
  return (byPrefix ?? null) as ProvinceName | null;
}
