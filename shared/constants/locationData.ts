export type CountryName = "Pakistan" | "Jordan";

export type PakistanProvinceName =
  | "Sindh"
  | "Punjab"
  | "Khyber Pakhtunkhwa"
  | "Balochistan"
  | "Islamabad Capital Territory"
  | "Azad Jammu & Kashmir"
  | "Gilgit-Baltistan";

export type JordanProvinceName =
  | "Amman Governorate"
  | "Zarqa Governorate"
  | "Irbid Governorate"
  | "Aqaba Governorate"
  | "Madaba Governorate"
  | "Balqa Governorate"
  | "Jerash Governorate"
  | "Ajloun Governorate"
  | "Karak Governorate"
  | "Ma'an Governorate"
  | "Mafraq Governorate"
  | "Tafilah Governorate";

export type ProvinceName = PakistanProvinceName | JordanProvinceName;

/** Strip BOM / odd whitespace from .env and API values. */
export function normalizeLocationString(
  raw: string | null | undefined
): string {
  return (raw ?? "")
    .replace(/^\uFEFF/, "")
    .replace(/\u00a0/g, " ")
    .trim();
}

/** Match API / user strings to a valid `CountryName` (trim, case-insensitive). */
export function parseCountryName(
  raw: string | null | undefined
): CountryName | null {
  const t = normalizeLocationString(String(raw)).toLowerCase();
  if (t === "jordan" || t === "jo" || t === "jor") {
    return "Jordan";
  }
  if (t === "pakistan" || t === "pk" || t === "pak") {
    return "Pakistan";
  }
  return null;
}

